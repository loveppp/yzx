import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {prepareProductImagePlan} from './product-image-plan.mjs';
const catalog=JSON.parse(readFileSync(new URL('../src/data/catalog.json',import.meta.url),'utf8'));
const legacy=JSON.parse(readFileSync(new URL('../src/data/catalog-legacy.json',import.meta.url),'utf8'));
const locales=['en','zh','vi'];
const groupIds=new Set(catalog.groups.map(g=>g.id));
const products=new Map(catalog.products.map(p=>[p.id,p]));
const destination=(id,locale)=>{const p=products.get(id);return p?`/${locale}/products/${p.group}/${p.id}/`:`/${locale}/products/${id}/`;};
const rules=['/ /en/ 302'];
for(const locale of locales){
  for(const [old,target] of Object.entries(legacy.categories)){
    if(!groupIds.has(old))rules.push(`/${locale}/products/${old}/ ${destination(target,locale)} 301`);
  }
  for(const [old,target] of Object.entries(legacy.products)){
    const from=`/${locale}/products/${old}/`,to=destination(target,locale);
    if(from!==to)rules.push(`${from} ${to} 301`);
  }
}
writeFileSync(new URL('../public/_redirects',import.meta.url),'# Generated by scripts/prepare-catalog.mjs; Cloudflare Pages legacy catalog redirects.\n'+rules.join('\n')+'\n');
mkdirSync(new URL('../data/catalog/',import.meta.url),{recursive:true});
const plan=prepareProductImagePlan(catalog);
console.log(`Prepared ${rules.length} legacy redirects, ${plan.jobs.length} main prompts, ${plan.detailJobs.length} detail prompts and ${plan.compositeJobs.length} composite briefs. No images generated.`);
